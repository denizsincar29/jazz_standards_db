export let currentLocale = localStorage.getItem('locale') || 'en';

export function t(key) {
    return LOCALES[currentLocale][key] || LOCALES.en[key] || key;
}

export function setLocale(lang) {
    currentLocale = lang;
    localStorage.setItem('locale', lang);
}

export function applyLocale() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        const val = t(key);
        if (val) el.textContent = val;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.dataset.i18nPlaceholder;
        const val = t(key);
        if (val) el.placeholder = val;
    });
    // Update locale toggle button text
    const btn = document.getElementById('locale-toggle-btn');
    if (btn) btn.textContent = currentLocale === 'en' ? 'RU' : 'EN';
}
